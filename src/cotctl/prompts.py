REASONIF_MULTI_TEMPLATE = (
    "Think step-by-step, and place only your final answer inside the tags `<answer>` and `</answer>`. "
    "Format your reasoning according to the following rules: {rules}"
    "\n\nHere is the question:\n\n{question}"
)


def multi_instruction(ctype: str, args: dict | None = None) -> str:
    """Instruction sentence for one constraint in the multi-constraint set. `capital` and
    `end_of_sentence` are ours; the rest reuse the ReasonIF wording (end phrase already localised)."""
    args = args or {}
    if ctype == "capital":
        return "When reasoning, your response should be in all capital letters."
    if ctype == "end_of_sentence":
        return f"When reasoning, end every sentence with the word '{args['end_word']}'."
    if ctype == "end_checker":
        return (
            f'When reasoning, finish your response with this exact phrase "{args["end_phrase"].strip()}". '
            "No other reasoning words should follow this phrase."
        )
    return reasonif_instruction(ctype, args)


def reasonif_multi_prompt(question: str, instructions: list[str]) -> str:
    rules = " ".join(f"**{i}**" for i in instructions)
    return REASONIF_MULTI_TEMPLATE.format(rules=rules, question=question)


REASONIF_TEMPLATE = (
    "Think step-by-step, and place only your final answer inside the tags `<answer>` and `</answer>`. "
    "Format your reasoning according to the following rule: **{instruction}**"
    "\n\nHere is the question:\n\n{question}"
)

# Same header without the format rule — used for stage-1 SFT rollouts and number_words calibration.
REASONIF_BASELINE_TEMPLATE = (
    "Think step-by-step, and place only your final answer inside the tags `<answer>` and `</answer>`."
    "\n\nHere is the question:\n\n{question}"
)


def reasonif_instruction(instruction_type: str, args: dict | None = None) -> str:
    """Render the instruction sentence for one ReasonIF constraint (upstream `build_description`)."""
    args = args or {}
    if instruction_type == "reasoning_language":
        name = LANGUAGE_NAMES[args["language"]].capitalize()
        return f"When reasoning, respond only in {name} language, no other language is allowed."
    if instruction_type == "number_words":
        return f"When reasoning, respond with less than {int(args['num_words'])} words."
    if instruction_type == "english_capital":
        return "When reasoning, your response should be in English and in all capital letters."
    if instruction_type == "end_checker":
        return (
            f'When reasoning, finish your response with this exact phrase "{args["end_phrase"].strip()}". '
            "No other reasoning words should follow this phrase."
        )
    if instruction_type == "json_format":
        return "When reasoning, your response should be wrapped in JSON format. You can use markdown ticks such as ```."
    if instruction_type == "no_comma":
        return "When reasoning, refrain from the use of any commas."
    raise ValueError(f"unknown ReasonIF instruction type: {instruction_type}")


def reasonif_prompt(question: str, instruction: str) -> str:
    return REASONIF_TEMPLATE.format(instruction=instruction, question=question)


def reasonif_baseline_prompt(question: str) -> str:
    return REASONIF_BASELINE_TEMPLATE.format(question=question)


